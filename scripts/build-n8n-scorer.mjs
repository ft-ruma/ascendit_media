// Generates n8n/score-lead.js from src/lib/scoring.ts, so n8n's Code node runs
// exactly the function the unit tests cover. Paste the output into the
// "Score lead" Code node (Run once for each item).
import { readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'

const src = readFileSync('src/lib/scoring.ts', 'utf8')
const js = ts
  .transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.None } })
  .outputText.replace(/^export /gm, '')
  .replace(/^"use strict";\n?/m, '')
  .replace(/Object\.defineProperty\(exports.*\n/g, '')
  .replace(/^exports\..*\n/gm, '')

const node = `// GENERATED by \`pnpm n8n:score\` from src/lib/scoring.ts. Do not edit here.
${js}
// ---- n8n Code node ("Run once for each item") ----
const lead = $json.body ?? $json
const est = lead.estimate ?? {}
const d = lead.derived ?? {}
const a = lead.answers ?? {}
const result = scoreLead({
  type: lead.type,
  pillars: a.what?.pillars ?? [],
  storeToSystem: !!d.storeToSystem,
  timeline: a.timeline,
  registered: a.business?.registered,
  size: a.business?.size,
  location: a.business?.location ?? (lead.attribution?.country && lead.attribution.country !== 'LK' ? 'overseas' : 'LK'),
  // Budget band and estimate share a currency only when the visitor kept it; compare like with like.
  budgetMax: d.budgetCur === est.cur ? (d.budgetMax ?? Number.MAX_SAFE_INTEGER) : undefined,
  estimateLow: est.low,
})
return { json: { ...lead, score: result.score, tier: result.tier, scoreReasons: result.reasons } }
`
writeFileSync('n8n/score-lead.js', node)
console.log('wrote n8n/score-lead.js')
